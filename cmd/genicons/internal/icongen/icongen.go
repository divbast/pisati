// listRE is the list of icons derived from Feather: Lucide names, joined
// by a comma and a space.
var listRE = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*(, [a-z0-9]+(-[a-z0-9]+)*)*$`)

// parseLicence reads lucide-static's LICENSE, which must be laid out as it
// is, line for line, blank lines aside:
//
//  1. the ISC License: its title, one copyright line, and its terms;
//  2. then, optionally and whole: the separator, the line introducing the
//     icons derived from Feather, the list of them, the MIT License's
//     title, one copyright line, and its terms.
//
// Only the two copyright holders and the list may vary. Any other line, a
// line missing, or anything after the end is an error, so that a change to
// Lucide's licensing stops the generator rather than pass unmarked.
func parseLicence(text string) (licensing, error) {
	var lic licensing
	lines := &licenceLines{}
	for line := range strings.SplitSeq(text, "\n") {
		if line = strings.TrimRight(line, " \t\r"); line != "" {
			lines.all = append(lines.all, line)
		}
	}
	var err error
	if err = lines.exact(iscTitle); err != nil {
		return lic, err
	}
	if lic.isc, err = lines.copyright(); err != nil {
		return lic, err
	}
	if err = lines.exact(iscText()...); err != nil {
		return lic, err
	}
	if lines.done() {
		return lic, nil
	}
	if err = lines.exact(separator, featherLine); err != nil {
		return lic, err
	}
	list, err := lines.next("the list of icons derived from Feather")
	if err != nil {
		return lic, err
	}
	if !listRE.MatchString(list) {
		return lic, fmt.Errorf("LICENSE: line %d is not a list of icons, as %q expects: %q", lines.at, featherLine, list)
	}
	lic.derived = strings.Split(list, ", ")
	if err = lines.exact(mitTitle); err != nil {
		return lic, err
	}
	if lic.mit, err = lines.copyright(); err != nil {
		return lic, err
	}
	if err = lines.exact(mitText()...); err != nil {
		return lic, err
	}
	if !lines.done() {
		return lic, fmt.Errorf("LICENSE: line %d follows the end of the MIT License: %q", lines.at+1, lines.all[lines.at])
	}
	return lic, nil
}

// licenceLines reads a LICENSE's lines that are not blank, in order.
type licenceLines struct {
	all []string
	// at is how many of all have been read.
	at int
}

// done reports whether every line has been read.
func (l *licenceLines) done() bool {
	return l.at == len(l.all)
}

// next reads the next line, which is what: an error if there is none.
func (l *licenceLines) next(what string) (string, error) {
	if l.done() {
		return "", fmt.Errorf("LICENSE: it ends where %s should be", what)
	}
	l.at++
	return l.all[l.at-1], nil
}

// exact reads one line for each of want, failing unless each is exactly
// its want.
func (l *licenceLines) exact(want ...string) error {
	for _, w := range want {
		got, err := l.next(fmt.Sprintf("%q", w))
		if err != nil {
			return err
		}
		if got != w {
			return fmt.Errorf("LICENSE: line %d is %q where lucide-static's has %q", l.at, got, w)
		}
	}
	return nil
}

// copyright reads a copyright line, and returns its holder.
func (l *licenceLines) copyright() (string, error) {
	line, err := l.next("a copyright line")
	if err != nil {
		return "", err
	}
	holder, ok := strings.CutPrefix(line, copyrightOf)
	if !ok || strings.TrimSpace(holder) == "" {
		return "", fmt.Errorf("LICENSE: line %d is %q where a copyright line should be", l.at, line)
	}
	return holder, nil
}

// nameRE is a Lucide icon's name: lower-case words joined by hyphens.
var nameRE = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)

// funcName returns the Go function name for the icon name: arrow-down
// becomes ArrowDown.
func funcName(name string) (string, error) {
	if !nameRE.MatchString(name) {
		return "", fmt.Errorf("%q is not a Lucide icon's name", name)
	}
	var b strings.Builder
	for word := range strings.SplitSeq(name, "-") {
		b.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return b.String(), nil
}

// rootAttrs returns the attributes an icon's svg element may have, which
// clean keeps but class: Lucide's own class names, which no page's CSS
// uses.
func rootAttrs() []string {
	return []string{
		"xmlns", "class", "width", "height", "viewBox", "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin",
	}
}

// shapeAttrs returns the attributes shape may have, its geometry and a
// fill, and whether shape is an element an icon draws with.
func shapeAttrs(shape string) ([]string, bool) {
	switch shape {
	case "path":
		return []string{"d", "fill"}, true
	case "circle":
		return []string{"cx", "cy", "r", "fill"}, true
	case "ellipse":
		return []string{"cx", "cy", "rx", "ry", "fill"}, true
	case "rect":
		return []string{"x", "y", "width", "height", "rx", "ry", "fill"}, true
	case "line":
		return []string{"x1", "y1", "x2", "y2"}, true
	case "polyline", "polygon":
		return []string{"points", "fill"}, true
	}
	return nil, false
}

// valueRE is every value an icon's attribute may take: numbers, path
// commands, colours by name and the SVG namespace.
var valueRE = regexp.MustCompile(`^[A-Za-z0-9 .,#%:/-]*$`)

// clean returns the icon in data, an SVG file as lucide-static writes
// one, as the SVG element a page shows: its svg element with
// aria-hidden="true" and without its class, holding its shapes, each
// with no children. It returns an error for anything else: another
// element or attribute, text, a processing instruction or a doctype, a
// value outside valueRE, or anything after the svg element but comments.
func clean(data []byte) (string, error) {
	dec := xml.NewDecoder(bytes.NewReader(data))
	var b strings.Builder
	depth, done := 0, false
	for {
		tok, err := dec.Token()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return "", err
		}
		switch tok := tok.(type) {
		case xml.Comment:
		case xml.CharData:
			if strings.TrimSpace(string(tok)) != "" {
				return "", errors.New("it holds text")
			}
		case xml.StartElement:
			if tok.Name.Space != svgNS {
				return "", fmt.Errorf("<%s> is outside the SVG namespace", tok.Name.Local)
			}
			switch {
			case depth == 0 && !done && tok.Name.Local == "svg":
				if err := writeElement(&b, tok, rootAttrs(), ` aria-hidden="true">`); err != nil {
					return "", err
				}
			case depth == 1:
				allowed, ok := shapeAttrs(tok.Name.Local)
				if !ok {
					return "", fmt.Errorf("<%s> is not a shape an icon draws with", tok.Name.Local)
				}
				if err := writeElement(&b, tok, allowed, "/>"); err != nil {
					return "", err
				}
			default:
				return "", fmt.Errorf("<%s> is where an icon has no element", tok.Name.Local)
			}
			depth++
		case xml.EndElement:
			depth--
			if depth == 0 {
				b.WriteString("</svg>")
				done = true
			}
		default:
			return "", fmt.Errorf("it holds a %T, which an icon does not", tok)
		}
	}
	if !done {
		return "", errors.New("it holds no svg element")
	}
	return b.String(), nil
}

// writeElement writes the start of el to b: its name and each of its
// attributes, which must be among allowed and have a value valueRE
// takes, then end. It leaves out class.
func writeElement(b *strings.Builder, el xml.StartElement, allowed []string, end string) error {
	b.WriteString("<" + el.Name.Local)
	for _, a := range el.Attr {
		key := a.Name.Local
		if a.Name.Space != "" || !slices.Contains(allowed, key) {
			return fmt.Errorf("<%s> has the attribute %q, which an icon does not use", el.Name.Local, attrName(a.Name))
		}
		if !valueRE.MatchString(a.Value) {
			return fmt.Errorf("<%s %s> has a value outside what SVG geometry needs: %q", el.Name.Local, key, a.Value)
		}
		if key == "xmlns" && a.Value != svgNS {
			return fmt.Errorf("<%s> names the namespace %q", el.Name.Local, a.Value)
		}
		if key == "class" {
			continue
		}
		b.WriteString(" " + key + `="` + html.EscapeString(a.Value) + `"`)
	}
	b.WriteString(end)
	return nil
}

// attrName returns n as its document spelt it, with its prefix.
func attrName(n xml.Name) string {
	if n.Space == "" {
		return n.Local
	}
	return n.Space + ":" + n.Local
}

// readFile returns the file name in fsys, checking ctx first.
func readFile(ctx context.Context, fsys fs.FS, name string) ([]byte, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	data, err := fs.ReadFile(fsys, name)
	if err != nil {
		return nil, err
	}
	return data, nil
}
