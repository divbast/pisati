// Command genicons writes internal/web/icons/icons.go: the Lucide icons
// Pisati's pages show, as inline SVG, read from the lucide-static package
// pnpm installs. Run it from the repository's root, as `just generate`
// does:
//
//	go run ./cmd/genicons
//
// It takes the icons named in the list below and nothing else. It keeps
// only the SVG elements and attributes Lucide draws with, and fails on
// anything else in an icon's file, so that an icon can never bring a
// script, a link or a style into a page. It marks the file with the
// licences its icons come under, as lucide-static's LICENSE gives them,
// and writes the same file for the same package every time.
package main

import (
	"bytes"
	"context"
	"encoding/xml"
	"errors"
	"fmt"
	"go/format"
	"html"
	"io"
	"io/fs"
	"os"
	"os/signal"
	"path"
	"regexp"
	"slices"
	"strings"
)

const (
	// lucideDir is where pnpm installs lucide-static, from the
	// repository's root.
	lucideDir = "node_modules/lucide-static"
	// outFile is the file genicons writes, from the repository's root.
	outFile = "internal/web/icons/icons.go"
	// svgNS is the SVG namespace, the only one an icon may use.
	svgNS = "http://www.w3.org/2000/svg"
	// ours is the copyright of the Go code genicons writes around the
	// icons.
	ours = "2026 Aryan Ameri <github@aryan.ameri.coffee>"
	// spdxLicence and spdxCopyright are the REUSE tags genicons writes,
	// each spelt in two, so that REUSE does not read them as this file's
	// own.
	spdxLicence   = "SPDX-" + "License-Identifier: "
	spdxCopyright = "SPDX-" + "FileCopyrightText: "
)

// names is the committed list of the icons Pisati's pages show, by their
// Lucide names. Adding one here, then running genicons, adds it to the
// icons package.
func names() []string {
	return []string{"monitor", "moon", "sun"}
}

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	err := generate(ctx, os.DirFS(lucideDir), names(), outFile)
	stop()
	if err != nil {
		fmt.Fprintln(os.Stderr, "genicons:", err)
		os.Exit(1)
	}
}

// generate writes the icons package for icons, read from src, the
// lucide-static package, to out.
func generate(ctx context.Context, src fs.FS, icons []string, out string) error {
	code, err := render(ctx, src, icons)
	if err != nil {
		return err
	}
	return os.WriteFile(out, code, 0o600)
}

// render returns the icons package's source for icons, read from src: the
// lucide-static package, with its LICENSE and an icons/<name>.svg for
// each. The icons come out in name order, whatever order icons is in. It
// returns an error, and no source, for an icon whose file holds anything
// but what lucide-static draws its icons with, or for a LICENSE laid out
// other than as lucide-static's is.
func render(ctx context.Context, src fs.FS, icons []string) ([]byte, error) {
	text, err := readFile(ctx, src, "LICENSE")
	if err != nil {
		return nil, err
	}
	lic, err := parseLicence(string(text))
	if err != nil {
		return nil, err
	}
	sorted := slices.Sorted(slices.Values(icons))
	var funcs bytes.Buffer
	derived := false
	for _, name := range sorted {
		fn, err := funcName(name)
		if err != nil {
			return nil, err
		}
		data, err := readFile(ctx, src, path.Join("icons", name+".svg"))
		if err != nil {
			return nil, err
		}
		svg, err := clean(data)
		if err != nil {
			return nil, fmt.Errorf("icons/%s.svg: %w", name, err)
		}
		terms := "under the ISC License"
		if slices.Contains(lic.derived, name) {
			derived = true
			terms = "derived from Feather's, under the MIT License"
		}
		fmt.Fprintf(&funcs, "\n// %s returns Lucide's %s icon, %s.\nfunc %s() Icon {\n\treturn Icon{svg: `%s`}\n}\n",
			fn, name, terms, fn, svg)
	}
	if derived && lic.mit == "" {
		return nil, errors.New("LICENSE: an icon is derived from Feather, but there is no MIT License for it")
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/genicons from lucide-static. DO NOT EDIT.\n\n")
	expr := "AGPL-3.0-only AND ISC"
	if derived {
		expr += " AND MIT"
	}
	b.WriteString("// " + spdxLicence + expr + "\n")
	b.WriteString("// " + spdxCopyright + ours + "\n")
	b.WriteString("// " + spdxCopyright + lic.isc + "\n")
	if derived {
		b.WriteString("// " + spdxCopyright + lic.mit + "\n")
	}
	b.WriteString(preamble)
	b.Write(funcs.Bytes())
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format the icons package: %w", err)
	}
	return formatted, nil
}

// preamble is the icons package's own code, which every icon's function
// follows.
const preamble = `
// Package icons holds the Lucide icons Pisati's pages show, as inline
// SVG, each from a function named for it. cmd/genicons writes it from
// the lucide-static package, keeping only the elements and attributes
// Lucide draws with, so an icon holds no script, link or style. Each
// icon is decorative, hidden from screen readers by aria-hidden, so
// whatever shows it gives its meaning in text.
package icons

import (
	"context"
	"io"
)

// Icon is one icon's SVG element. It is a templ.Component, which a
// template renders with @. The zero Icon renders nothing.
type Icon struct {
	svg string
}

// Render writes the icon's SVG element to w.
func (i Icon) Render(_ context.Context, w io.Writer) error {
	_, err := io.WriteString(w, i.svg)
	return err
}
`

// licensing is what lucide-static's LICENSE says: who holds the copyright
// of its icons under the ISC License, which icons are derived from
// Feather, and who holds theirs, under the MIT License.
type licensing struct {
	isc, mit string
	derived  []string
}

// featherLine introduces the list of icons derived from Feather.
const featherLine = "The following Lucide icons are derived from the Feather project:"

// parseLicence reads lucide-static's LICENSE, laid out as it is: the ISC
// License with its copyright line; then, optionally, the line introducing
// the icons derived from Feather, a line listing them, and the MIT
// License with its copyright line. Anything else is an error, so that a
// change to Lucide's licensing stops the generator rather than pass
// unmarked.
func parseLicence(text string) (licensing, error) {
	var lic licensing
	lines := strings.Split(text, "\n")
	if strings.TrimSpace(lines[0]) != "ISC License" {
		return lic, errors.New("LICENSE: it does not start with the ISC License")
	}
	inMIT := false
	for i, line := range lines {
		line = strings.TrimSpace(line)
		holder, isCopyright := strings.CutPrefix(line, "Copyright (c) ")
		switch {
		case isCopyright && inMIT && lic.mit == "":
			lic.mit = holder
		case isCopyright && !inMIT && lic.isc == "":
			lic.isc = holder
		case line == featherLine:
			list, err := nextLine(lines[i+1:])
			if err != nil {
				return lic, err
			}
			for name := range strings.SplitSeq(list, ",") {
				lic.derived = append(lic.derived, strings.TrimSpace(name))
			}
		case strings.HasPrefix(line, "The MIT License (MIT)"):
			inMIT = true
		}
	}
	if lic.isc == "" {
		return lic, errors.New("LICENSE: the ISC License has no copyright line")
	}
	if inMIT && lic.mit == "" {
		return lic, errors.New("LICENSE: the MIT License has no copyright line")
	}
	return lic, nil
}

// nextLine returns the first line of lines that is not blank.
func nextLine(lines []string) (string, error) {
	for _, l := range lines {
		if l = strings.TrimSpace(l); l != "" {
			return l, nil
		}
	}
	return "", errors.New("LICENSE: no icons follow the line introducing those derived from Feather")
}

// nameRE is a Lucide icon's name: lower-case words joined by hyphens.
var nameRE = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)

// funcName returns the Go function name for the icon name: arrow-down
// becomes ArrowDown.
func funcName(name string) (string, error) {
	if !nameRE.MatchString(name) {
		return "", fmt.Errorf("%q is not a Lucide icon's name", name)
	}
	var b strings.Builder
	for word := range strings.SplitSeq(name, "-") {
		b.WriteString(strings.ToUpper(word[:1]) + word[1:])
	}
	return b.String(), nil
}

// rootAttrs are the attributes an icon's svg element may have, which it
// keeps but class: Lucide's own class names, which no page's CSS uses.
var rootAttrs = []string{
	"xmlns", "class", "width", "height", "viewBox", "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin",
}

// shapes are the elements an icon may draw with, each with the
// attributes it may have: its geometry, and a fill.
var shapes = map[string][]string{
	"path":     {"d", "fill"},
	"circle":   {"cx", "cy", "r", "fill"},
	"ellipse":  {"cx", "cy", "rx", "ry", "fill"},
	"rect":     {"x", "y", "width", "height", "rx", "ry", "fill"},
	"line":     {"x1", "y1", "x2", "y2"},
	"polyline": {"points", "fill"},
	"polygon":  {"points", "fill"},
}

// valueRE is every value an icon's attribute may take: numbers, path
// commands, colours by name and the SVG namespace.
var valueRE = regexp.MustCompile(`^[A-Za-z0-9 .,#%:/-]*$`)

// clean returns the icon in data, an SVG file as lucide-static writes
// one, as the SVG element a page shows: its svg element with
// aria-hidden="true" and without its class, holding its shapes, each
// with no children. It returns an error for anything else: another
// element or attribute, text, a processing instruction or a doctype, a
// value outside valueRE, or anything after the svg element but comments.
func clean(data []byte) (string, error) {
	dec := xml.NewDecoder(bytes.NewReader(data))
	var b strings.Builder
	depth, done := 0, false
	for {
		tok, err := dec.Token()
		if errors.Is(err, io.EOF) {
			break
		}
		if err != nil {
			return "", err
		}
		switch tok := tok.(type) {
		case xml.Comment:
		case xml.CharData:
			if strings.TrimSpace(string(tok)) != "" {
				return "", errors.New("it holds text")
			}
		case xml.StartElement:
			if tok.Name.Space != svgNS {
				return "", fmt.Errorf("<%s> is outside the SVG namespace", tok.Name.Local)
			}
			switch {
			case depth == 0 && !done && tok.Name.Local == "svg":
				if err := writeElement(&b, tok, rootAttrs, ` aria-hidden="true">`); err != nil {
					return "", err
				}
			case depth == 1:
				allowed, ok := shapes[tok.Name.Local]
				if !ok {
					return "", fmt.Errorf("<%s> is not a shape an icon draws with", tok.Name.Local)
				}
				if err := writeElement(&b, tok, allowed, "/>"); err != nil {
					return "", err
				}
			default:
				return "", fmt.Errorf("<%s> is where an icon has no element", tok.Name.Local)
			}
			depth++
		case xml.EndElement:
			depth--
			if depth == 0 {
				b.WriteString("</svg>")
				done = true
			}
		default:
			return "", fmt.Errorf("it holds a %T, which an icon does not", tok)
		}
	}
	if !done {
		return "", errors.New("it holds no svg element")
	}
	return b.String(), nil
}

// writeElement writes the start of el to b: its name and each of its
// attributes, which must be among allowed and have a value valueRE
// takes, then end. It leaves out class.
func writeElement(b *strings.Builder, el xml.StartElement, allowed []string, end string) error {
	b.WriteString("<" + el.Name.Local)
	for _, a := range el.Attr {
		key := a.Name.Local
		if a.Name.Space != "" || !slices.Contains(allowed, key) {
			return fmt.Errorf("<%s> has the attribute %q, which an icon does not use", el.Name.Local, attrName(a.Name))
		}
		if !valueRE.MatchString(a.Value) {
			return fmt.Errorf("<%s %s> has a value outside what SVG geometry needs: %q", el.Name.Local, key, a.Value)
		}
		if key == "xmlns" && a.Value != svgNS {
			return fmt.Errorf("<%s> names the namespace %q", el.Name.Local, a.Value)
		}
		if key == "class" {
			continue
		}
		b.WriteString(" " + key + `="` + html.EscapeString(a.Value) + `"`)
	}
	b.WriteString(end)
	return nil
}

// attrName returns n as its document spelt it, with its prefix.
func attrName(n xml.Name) string {
	if n.Space == "" {
		return n.Local
	}
	return n.Space + ":" + n.Local
}

// readFile returns the file name in fsys, checking ctx first.
func readFile(ctx context.Context, fsys fs.FS, name string) ([]byte, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	data, err := fs.ReadFile(fsys, name)
	if err != nil {
		return nil, err
	}
	return data, nil
}
